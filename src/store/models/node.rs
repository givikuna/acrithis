use chrono::{DateTime, Utc};
use serde::{Deserialize, Serialize};

use super::dependency::Dependency;
use super::enums::{NodeType, TrustLevel, ValidationStatus};

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Node {
    pub hash: String,

    pub name: String,
    pub node_type: NodeType,

    pub lean_source: String,
    pub doc_markdown: String,

    pub dependencies: Vec<Dependency>,
    pub closure_depth: u32,

    pub lean_version: String,

    pub created_at: DateTime<Utc>,
    pub created_by: String,
    pub validation_status: ValidationStatus,
    pub trust_level: TrustLevel,
    pub size_bytes: u64,
    pub has_sorry: bool,
    pub tags: Vec<String>,
}

impl Node {
    /*
        Assisted By: DeepSeek
        buffer.extend_from_slice calls were generated by DeepSeek based on documentation
    */
    pub fn canonical_bytes(&self, lean_sha_hex: &str, doc_sha_hex: &str) -> Vec<u8> {
        let mut buffer: Vec<u8> = Vec::new();

        buffer.extend_from_slice(b"acrithis-node-v1\0");

        buffer.extend_from_slice(b"name\0");
        buffer.extend_from_slice(self.name.as_bytes());
        buffer.extend_from_slice(b"\0");

        buffer.extend_from_slice(b"type\0");
        let type_str: String = serde_json::to_string(&self.node_type)
            .unwrap_or_else(|_| "\"unknown\"".to_string())
            .replace('"', "");
        buffer.extend_from_slice(type_str.as_bytes());
        buffer.extend_from_slice(b"\0");

        buffer.extend_from_slice(b"lean_version\0");
        buffer.extend_from_slice(self.lean_version.as_bytes());
        buffer.extend_from_slice(b"\0");

        buffer.extend_from_slice(b"lean_sha\0");
        buffer.extend_from_slice(lean_sha_hex.as_bytes());
        buffer.extend_from_slice(b"\0");

        // 6. Doc SHA
        buffer.extend_from_slice(b"doc_sha\0");
        buffer.extend_from_slice(doc_sha_hex.as_bytes());
        buffer.extend_from_slice(b"\0");

        let mut sorted_deps: Vec<Dependency> = self.dependencies.clone();
        sorted_deps.sort();

        buffer.extend_from_slice(b"deps\0");
        buffer.extend_from_slice(sorted_deps.len().to_string().as_bytes());
        buffer.extend_from_slice(b"\0");

        for dep in sorted_deps {
            buffer.extend_from_slice(b"dep\0");
            buffer.extend_from_slice(dep.to_hash.as_bytes());
            buffer.extend_from_slice(b"\0");

            let role_str: String = serde_json::to_string(&dep.role)
                .unwrap_or_else(|_| "\"uses\"".to_string())
                .replace('"', "");
            buffer.extend_from_slice(role_str.as_bytes());
            buffer.extend_from_slice(b"\0");
        }

        buffer
    }
}
